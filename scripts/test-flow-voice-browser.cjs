// Browser integration: actual planner hooks/tools/MapLibre, synthetic routing and blank test map style.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { completeFixture } = require('./lib/smart-journey-fixture.cjs');
const base = process.env.VOICE_TEST_URL || 'http://localhost:5173';
const output = process.env.VOICE_TEST_OUTPUT || '/tmp/vlaiq-voice-tests';
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--enable-unsafe-swiftshader'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const page = await context.newPage(), errors = [], requests = [];
    page.on('pageerror', (e) => { errors.push(e.message); console.error('PAGE ERROR:', e.message); });
    let delay = 0, unavailable = false;
    await page.route('**/api/journeys/complete', async (route) => {
      const body = route.request().postDataJSON(); requests.push(body);
      if (delay) await new Promise((r) => setTimeout(r, delay));
      if (unavailable) return route.fulfill({ status: 503, json: { error: { message: 'SYNTHETIC SERVICE OUTAGE' } } }).catch(() => {});
      const fixture = completeFixture(body);
      fixture.journeys = fixture.journeys.filter((j) => body.modes.includes(j.category));
      const ids = new Set(fixture.journeys.map((j) => j.id));
      for (const r of Object.values(fixture.rankings)) { r.ids = r.ids.filter((id) => ids.has(id)); r.recommendedId = r.ids[0] ?? null; }
      if (fixture.opportunity && !ids.has(fixture.opportunity.journeyId)) fixture.opportunity = null;
      return route.fulfill({ json: fixture }).catch(() => {});
    });
    await page.route('https://tiles.openfreemap.org/**', (r) => r.fulfill({ json: { version: 8, sources: {}, layers: [{ id: 'test-blank', type: 'background', paint: { 'background-color': '#102016' } }] } }));
    await page.route('**/flow-voice-test', (r) => r.fulfill({ contentType: 'text/html', body: '<div id="root"></div><script type="module">import RefreshRuntime from "/@react-refresh"; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;</script><script type="module" src="/flow-voice-harness.tsx"></script>' }));
    await page.goto(`${base}/flow-voice-test`);
    await page.waitForFunction(() => window.flowHarness);
    const call = (name, input) => page.evaluate(([n, i]) => window.flowHarness.call(n, i), [name, input]);
    await page.evaluate(() => window.flowHarness.begin());
    assert.equal((await call('get_journey_context', {})).data.origin, null);
    assert.equal((await call('compare_journeys', { destination_text: 'Piața de test' })).error.code, 'MISSING_ORIGIN');
    assert.equal((await call('compare_journeys', { origin_text: 'Gara de test', destination_text: 'Biblioteca' })).error.code, 'AMBIGUOUS_LOCATION');
    assert.equal((await call('update_journey_preferences', { max_walking_minutes: 5 })).ok, true);
    await page.waitForTimeout(80);
    const first = await call('compare_journeys', { origin_text: 'Gara de test', destination_text: 'Piața de test' });
    assert.equal(first.ok, true, JSON.stringify(first));
    assert.equal(first.data.environment, 'demo');
    assert(!first.data.journeys.some((j) => j.walking_minutes > 5));
    assert(!JSON.stringify(first).includes('geometry'));
    await page.getByRole('group', { name: 'Călătorii calculate' }).waitFor();
    const car = first.data.journeys.find((j) => j.journey_mode === 'driving');
    assert.equal(car.duration_minutes, 8); assert.equal(car.walking_minutes, 3);
    const selected = await call('select_and_explain_journey', { comparison_id: first.data.comparison_id, journey_id: car.journey_id });
    assert.equal(selected.ok, true, JSON.stringify(selected)); assert.equal(selected.data.map_highlighted, true, JSON.stringify(selected));
    await page.evaluate(() => window.flowHarness.begin());
    const restarted = await call('get_journey_context', {});
    assert.equal(restarted.data.selected_journey.journey_id, car.journey_id);
    assert.notEqual(restarted.data.comparison.comparison_id, first.data.comparison_id);
    assert.equal((await call('select_and_explain_journey', { comparison_id: first.data.comparison_id, journey_id: car.journey_id })).error.code, 'STALE_CONTEXT');
    await call('update_journey_preferences', { priority: 'cheapest' });
    await page.waitForTimeout(80);
    const cheaper = await call('compare_journeys', {});
    assert.equal(cheaper.ok, true, JSON.stringify(cheaper));
    assert.equal(requests.at(-1).maxWalkMinutes, 5); assert.equal(requests.at(-1).parkingPreference, 'cheap');
    assert.equal((await call('select_and_explain_journey', { comparison_id: first.data.comparison_id, journey_id: car.journey_id })).error.code, 'STALE_CONTEXT');
    const bike = await call('compare_journeys', { journey_mode: 'cycling' });
    assert.equal(bike.ok, true, JSON.stringify(bike));
    assert.deepEqual(requests.at(-1).modes, ['cycle']);
    assert.equal((await call('get_journey_context', {})).data.preferences.journey_mode, 'driving');
    await page.getByRole('button', { name: 'Toggle map' }).click();
    const noMap = await call('select_and_explain_journey', { comparison_id: bike.data.comparison_id, journey_id: bike.data.journeys[0].journey_id });
    assert.equal(noMap.data.map_highlighted, false);
    delay = 300;
    const pending = call('compare_journeys', {});
    await page.waitForTimeout(50); await page.getByRole('button', { name: 'Manual limit 7' }).click();
    assert.equal((await pending).error.code, 'STALE_CONTEXT');
    assert.equal((await call('get_journey_context', {})).data.preferences.max_walking_minutes, 7);
    delay = 0; unavailable = true;
    assert.equal((await call('compare_journeys', {})).error.code, 'SERVICE_UNAVAILABLE');
    unavailable = false; delay = 300;
    const stopped = call('compare_journeys', {}); await page.waitForTimeout(50); await page.evaluate(() => window.flowHarness.end());
    assert.equal((await stopped).error.code, 'STALE_CONTEXT');
    assert.deepEqual(errors, []);
    await page.screenshot({ path: `${output}/planner-synthetic.png`, fullPage: true });
    // Actual application: keyboard-accessible activation, permission rejection, small viewport and reduced motion.
    const app = await context.newPage();
    await app.setViewportSize({ width: 390, height: 844 }); await app.emulateMedia({ reducedMotion: 'reduce' });
    await app.route('https://tiles.openfreemap.org/**', (r) => r.fulfill({ json: { version: 8, sources: {}, layers: [{ id: 'blank', type: 'background' }] } }));
    await app.addInitScript(() => { Object.defineProperty(navigator.mediaDevices, 'getUserMedia', { value: async () => { throw new DOMException('Synthetic permission rejection', 'NotAllowedError'); } }); });
    await app.goto(base);
    const start = app.getByRole('button', { name: 'Pornește FLOW Voice' });
    await start.focus(); await app.keyboard.press('Enter');
    await app.getByRole('alert').filter({ hasText: 'microfon a fost refuzat' }).waitFor({ timeout: 5000 }).catch(async (error) => { console.log('VOICE STATE', await app.locator('.flow-voice').allTextContents()); await app.screenshot({ path: `${output}/permission-debug.png`, fullPage: true }); throw error; });
    assert.equal(await app.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await app.screenshot({ path: `${output}/mobile-permission-denied.png`, fullPage: true });
    await app.close();
    console.log(JSON.stringify({ result: 'PASS', routing: 'SYNTHETIC FIXTURES', map: 'REAL MAPLIBRE with blank test style', assertions: 'context; 5-minute/cheaper preservation; total vs walking; map true/false; stale selection; cycling temporary; manual race; outage; ended session; keyboard; permission; mobile', requests: requests.length, errors, output }));
  } finally { await browser.close(); }
})().catch((e) => { console.error(e); process.exitCode = 1; });
